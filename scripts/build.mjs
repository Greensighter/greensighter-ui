// Generates css/tokens.css from tokens/tokens.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PREFIX = 'gs';
const root = new URL('..', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens/tokens.json', root), 'utf8'));

const varName = path => `--${PREFIX}-${path.join('-')}`;
const ref = value => value.replace(/\{([^}]+)\}/g, (_, p) => `var(${varName(p.split('.'))})`);

function cssValue(value, type) {
  if (type === 'fontFamily' && Array.isArray(value)) {
    return value.map(f => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
  }
  return typeof value === 'string' ? ref(value) : String(value);
}

// Walks a token group, yielding [path, value, type] for every leaf.
function* leaves(node, path = [], type) {
  type = node.$type ?? type;
  if ('$value' in node) return yield [path, node.$value, type];
  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith('$')) yield* leaves(child, [...path, key], type);
  }
}

const decls = (group, base = []) =>
  [...leaves(group, base)].map(([p, v, t]) => `  ${varName(p)}: ${cssValue(v, t)};`).join('\n');

const { theme, 'text-style': textStyles, ...primitives } = tokens;

const textClasses = [...leaves(textStyles)].map(([[name], v]) => `.${PREFIX}-text-${name} {
  font-family: ${ref(v.fontFamily)};
  font-weight: ${ref(v.fontWeight)};
  font-size: ${ref(v.fontSize)};
  line-height: ${ref(v.lineHeight)};
  letter-spacing: ${v.letterSpacing};
}`).join('\n\n');

const css = `/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit by hand. */

:root {
${Object.entries(primitives).filter(([k]) => !k.startsWith('$')).map(([k, g]) => decls(g, [k])).join('\n')}
}

/* Dark is the default theme. */
:root,
[data-theme="dark"] {
  color-scheme: dark;
${decls(theme.dark)}
}

[data-theme="light"] {
  color-scheme: light;
${decls(theme.light)}
}

${textClasses}
`;

mkdirSync(new URL('css/', root), { recursive: true });
writeFileSync(new URL('css/tokens.css', root), css);
console.log('Wrote css/tokens.css');

// Keep the showcase page's embedded token data in sync.
const pageUrl = new URL('index.html', root);
const page = readFileSync(pageUrl, 'utf8');
const data = JSON.stringify(tokens).replace(/</g, '\\u003c');
writeFileSync(pageUrl, page.replace(
  /(<script id="tokens" type="application\/json">)[\s\S]*?(<\/script>)/,
  `$1${data}$2`,
));
console.log('Updated index.html');
